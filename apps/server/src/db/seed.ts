/* ═══════════════ 工具 ═══════════════ */

const NOW = (): Date => new Date();

function iso(d: Date): string {
  return d.toISOString().replace(/\.\d{3}Z$/, 'Z');
}

function minutesAgo(n: number): string {
  return iso(new Date(NOW().getTime() - n * 60_000));
}

function hoursAgo(n: number): string {
  return iso(new Date(NOW().getTime() - n * 3_600_000));
}

function daysAgo(n: number): string {
  return iso(new Date(NOW().getTime() - n * 86_400_000));
}

function hoursFromNow(n: number): string {
  return iso(new Date(NOW().getTime() + n * 3_600_000));
}

/** 固定时间戳（种子内保持一致，避免每次运行漂移） */
const T0 = hoursAgo(72);

type Row = Record<string, unknown>;

/** 幂等插入：`INSERT OR IGNORE` */
function ins(db: Db, table: string, row: Row): void {
  const cols = Object.keys(row);
  const placeholders = cols.map(() => '?').join(', ');
  db.run(
    `INSERT OR IGNORE INTO ${table} (${cols.join(', ')}) VALUES (${placeholders})`,
    cols.map((c) => row[c]),
  );
}

function insMany(db: Db, table: string, rows: Row[]): void {
  for (const row of rows) ins(db, table, row);
}

