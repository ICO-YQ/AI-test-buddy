export interface SeedSummary {
  workspace: number;
  boardColumn: number;
  member: number;
  agentConfig: number;
  model: number;
  sceneRoute: number;
  task: number;
  skill: number;
  hubRepo: number;
  hubSkill: number;
  kbSpace: number;
  kbDocument: number;
  audit: number;
  usage: number;
}

function count(db: Db, table: string): number {
  const row = db.get<{ c: number }>(`SELECT COUNT(*) AS c FROM ${table}`);
  return row ? Number(row.c) : 0;
}

/**
 * 写入全部种子数据（幂等：固定 ID + INSERT OR IGNORE）
 * @param db 数据库连接，默认取全局单例
 */
export function seed(db: Db = openDb()): SeedSummary {
  migrate(db);

  db.tx(() => {
    seedWorkspaceAndBoard(db);
    seedModels(db);
    seedMembers(db);
    seedHub(db);
    seedSkills(db);
    seedKnowledge(db); // kb_space 需早于 session
    seedTasks(db);
    seedSessions(db);
    seedGovernance(db);
  });

  return {
    workspace: count(db, 'workspace'),
    boardColumn: count(db, 'board_column'),
    member: count(db, 'member'),
    agentConfig: count(db, 'agent_config'),
    model: count(db, 'model_config'),
    sceneRoute: count(db, 'scene_route'),
    task: count(db, 'task'),
    skill: count(db, 'skill'),
    hubRepo: count(db, 'hub_repo'),
    hubSkill: count(db, 'hub_skill'),
    kbSpace: count(db, 'kb_space'),
    kbDocument: count(db, 'kb_document'),
    audit: count(db, 'audit_log'),
    usage: count(db, 'usage_record'),
  };
}

/* ═══════════════ CLI ═══════════════ */

async function runCli(): Promise<void> {
  const { pathToFileURL } = await import('node:url');
  const entry = process.argv[1];
  if (!entry || import.meta.url !== pathToFileURL(entry).href) return;
  const summary = seed();
  console.log(`[seed] 种子数据写入完成（幂等）：${JSON.stringify(summary, null, 2)}`);
}

